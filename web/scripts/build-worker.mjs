// Bundles each worker into a plain static script — outside the app bundler
// on purpose (bundler-worker interop broke silently under static export; a
// plain script URL cannot). Filenames are content-hashed so a cached stale
// worker can never run against fresh app code; each URL is emitted as a
// generated module the client imports (and prefixes with the base path).
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, rmSync, renameSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const WORKERS = [
  { entry: 'src/engine/worker/engine.worker.ts', prefix: 'engine.worker', urlFile: 'src/engine/worker/worker-url.ts' },
  { entry: 'src/cuda/worker/cuda.worker.ts', prefix: 'cuda.worker', urlFile: 'src/cuda/worker/worker-url.ts' },
];

for (const w of WORKERS) {
  const TMP = `public/${w.prefix}.tmp.js`;
  await build({
    entryPoints: [w.entry],
    bundle: true,
    format: 'iife',
    outfile: TMP,
    logLevel: 'warning',
    alias: { '@': './src' },
  });
  const hash = createHash('sha256').update(readFileSync(TMP)).digest('hex').slice(0, 10);
  const name = `${w.prefix}.${hash}.js`;
  const re = new RegExp(`^${w.prefix.replace('.', '\\.')}\\.[0-9a-f]{10}\\.js$`);
  for (const f of readdirSync('public')) {
    const stale = (re.test(f) && f !== name) || f === `${w.prefix}.js`;
    if (stale) rmSync(`public/${f}`);
  }
  renameSync(TMP, `public/${name}`);
  writeFileSync(
    w.urlFile,
    `// generated by scripts/build-worker.mjs — do not edit\nexport const WORKER_URL = '/${name}';\n`,
  );
  console.log(`bundled ${name}`);
}
