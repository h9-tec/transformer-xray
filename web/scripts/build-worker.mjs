// Bundles the engine worker into a plain static script — outside the app
// bundler on purpose (bundler-worker interop broke silently under static
// export; a plain script URL cannot). The filename is content-hashed so a
// cached stale worker can never run against fresh app code; the URL is
// emitted as a generated module the client imports.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, rmSync, renameSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const TMP = 'public/engine.worker.tmp.js';
await build({
  entryPoints: ['src/engine/worker/engine.worker.ts'],
  bundle: true,
  format: 'iife',
  outfile: TMP,
  logLevel: 'warning',
});

const hash = createHash('sha256').update(readFileSync(TMP)).digest('hex').slice(0, 10);
const name = `engine.worker.${hash}.js`;

for (const f of readdirSync('public')) {
  const stale =
    (/^engine\.worker\.[0-9a-f]{10}\.js$/.test(f) && f !== name) || f === 'engine.worker.js';
  if (stale) rmSync(`public/${f}`);
}
renameSync(TMP, `public/${name}`);

writeFileSync(
  'src/engine/worker/worker-url.ts',
  `// generated by scripts/build-worker.mjs — do not edit\nexport const WORKER_URL = '/${name}';\n`,
);
console.log(`bundled ${name}`);
